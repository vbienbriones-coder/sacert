/**
 * Returns the list of barangays for a given municipality.
 * Falls back to San Andres if municipality is not found.
 */
export function getBarangaysByMunicipality(municipality: string): string[] {
  if (!municipality) return CATANDUANES_BARANGAYS['San Andres'];

  // Normalize lookup (handle cases like "Panganiban (Payo)" or "San Andres (Calolbon)")
  const clean = municipality.trim();
  if (CATANDUANES_BARANGAYS[clean]) {
    return CATANDUANES_BARANGAYS[clean];
  }

  const matchKey = Object.keys(CATANDUANES_BARANGAYS).find(
    (k) => clean.toLowerCase().startsWith(k.toLowerCase()) || k.toLowerCase().startsWith(clean.toLowerCase())
  );

  return matchKey ? CATANDUANES_BARANGAYS[matchKey] : CATANDUANES_BARANGAYS['San Andres'];
}
